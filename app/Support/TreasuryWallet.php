<?php

namespace App\Support;

use App\Models\SiteSetting;

/**
 * ที่อยู่กระเป๋าที่ใช้ "จ่ายเหรียญ TPIX ออก" — แหล่งความจริงเดียวของทั้งระบบ.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * เจ้าของกำหนด: ใช้กระเป๋าใบเดียวกับที่รับค่าบริการ
 * ═══════════════════════════════════════════════════════════════════════════
 * เดิมมีกระเป๋าสองใบแยกกัน — กระเป๋าร้อนสำหรับจ่าย (`0x78B81dF5…`) กับกระเป๋า
 * รับค่าบริการ (`revenue.tpix_wallet`) ซึ่งแปลว่าต้องดูแลคีย์สองชุด เติมเงินสองที่
 * และค่าบริการที่เก็บมาเป็น TPIX ก็กองอยู่คนละใบกับใบที่ใช้จ่ายลูกค้า
 *
 * รวมเป็นใบเดียวแล้ว: ค่าบริการที่เก็บได้ไหลกลับมาเป็นทุนสำหรับจ่ายเหรียญเอง
 * และเหลือคีย์ชุดเดียวที่ต้องเก็บให้ดี
 *
 * ⚠️ ถ้าแอดมินเปลี่ยนกระเป๋ารับค่าบริการ ที่อยู่ตรงนี้จะเปลี่ยนตามทันที
 *    แล้ว keystore ที่วางไว้บนเซิร์ฟเวอร์จะไม่ตรงกับที่อยู่ใหม่
 *    → HotWalletSigner ตรวจ TPIX_EXPECT_ADDRESS แล้วปฏิเสธการเซ็น (fail-closed)
 *    ไม่ใช่จ่ายเงินออกจากกระเป๋าผิดใบ ซึ่งเป็นพฤติกรรมที่ต้องการ
 *
 * Developed by Xman Studio.
 */
class TreasuryWallet
{
    /**
     * ที่อยู่กระเป๋าจ่ายเหรียญ — ค่าจากหลังบ้านมาก่อน แล้วค่อย .env/config.
     */
    public static function address(): string
    {
        $fromSetting = trim((string) SiteSetting::get('revenue', 'tpix_wallet', ''));

        if ($fromSetting !== '') {
            return $fromSetting;
        }

        return (string) config('treasury.hot_wallet.address', '');
    }

    /**
     * ตั้งค่ากระเป๋าไว้แล้วหรือยัง.
     */
    public static function isConfigured(): bool
    {
        return preg_match('/^0x[a-fA-F0-9]{40}$/', self::address()) === 1;
    }
}
